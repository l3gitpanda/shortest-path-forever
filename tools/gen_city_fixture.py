#!/usr/bin/env python3
"""Generate tests/fixtures/city_places.lua: where NPCs with a service or a quest stand in the six capitals, for
tests/city_walks_spec.lua (stdlib).

The walking maps are baked from the client's collision and nothing in the repository says where a player actually
walks to. classic-db's creature spawns do: an NPC a player talks to stands on a floor a player can reach, at a height
the server stores. Each capital gets its flight master as the hub and an even sample of its other NPCs that stand
still (MovementType 0), have an NPC flag and do not fly, one per 8 yd square.

    python3 tools/gen_city_fixture.py            # fetches the pinned classic-db once into tools/.cache
    python3 tools/gen_city_fixture.py --offline  # cache only
"""

import argparse
import csv
import gzip

from gen_heights import ENTRY, FLIES, INHABIT, NPC_FLAGS, TUPLES
from gen_routes import CACHE, ROOT
from gen_transit import DB_REV, DB_URL

try:
    from tools.forever_tools.fsio import publish
    from tools.forever_tools.wago import fetch
except ModuleNotFoundError:
    from forever_tools.fsio import publish
    from forever_tools.wago import fetch

OUTPUT = ROOT / "tests" / "fixtures" / "city_places.lua"
NAME = 1
# A capital's continent, its zone map's box in world yards (Data/Zones.lua) and its flight master's creature ID.
# Darnassus has no flight master: its hub is the bank, where the portal from Rut'theran Village lets out.
CITIES = {
    "Stormwind": (0, (-9154, -15, -7996, 1723), 352),
    "Ironforge": (0, (-5097, -1504, -4569, -714), 1573),
    "Undercity": (0, (1238, -86, 1878, 873), 4551),
    "Orgrimmar": (1, (1338, -5083, 2274, -3681), 3310),
    "Thunder Bluff": (1, (-1546, -527, -850, 517), 2995),
    "Darnassus": (1, (9533, 1880, 10238, 2938), 4155),
}
# Places kept per capital, besides the hub.
SAMPLE = 60
# One place per square this many yards wide: a walking-map cell (Routing/PathGrid.lua).
CELL = 8


def creatures(offline=False):
    """Each still, flagged, ground creature spawn as (map, creature ID, name, x, y, z)."""
    path = CACHE / f"classicdb-{DB_REV[:8]}.sql.gz"
    fetch(DB_URL, path, user_agent="ShortestPathForever/1.0", offline=offline, timeout=60, validate=gzip.decompress)
    names, spawns = {}, []
    with gzip.open(path, "rt", encoding="utf-8") as stream:
        for line in stream:
            if line.startswith("INSERT INTO `creature_template` VALUES "):
                for match in TUPLES.finditer(line):
                    row = next(csv.reader([match[1]], quotechar="'", escapechar="\\"))
                    if int(row[NPC_FLAGS]) and not int(row[INHABIT]) & FLIES:
                        names[int(row[ENTRY])] = row[NAME]
            elif line.startswith("INSERT INTO `creature` VALUES "):
                for match in TUPLES.finditer(line):
                    row = match[1].split(",")
                    if row[11] == "0":
                        spawns.append((int(row[2]), int(row[1]), float(row[4]), float(row[5]), float(row[6])))
    if not names or not spawns:
        raise ValueError("classic-db: missing creature or creature_template rows")
    return [(m, npc, names[npc], x, y, z) for m, npc, x, y, z in spawns if npc in names]


def sample(rows):
    """An even sample of rows, first and last included, in their own order."""
    if len(rows) <= SAMPLE:
        return rows
    return [rows[round(i * (len(rows) - 1) / (SAMPLE - 1))] for i in range(SAMPLE)]


def places(found):
    """{city: (map, hub, [place, ...])}, a place being (name, x, y, z) rounded to a tenth of a yard."""
    out = {}
    for city, (map_id, (x0, y0, x1, y1), hub_id) in CITIES.items():
        inside = sorted(
            (name, round(x, 1), round(y, 1), round(z, 1), npc)
            for m, npc, name, x, y, z in found
            if m == map_id and x0 <= x <= x1 and y0 <= y <= y1
        )
        hubs = [row for row in inside if row[4] == hub_id]
        if len(hubs) != 1:
            raise ValueError(f"{city}: expected one spawn of creature {hub_id}, found {len(hubs)}")
        seen, rest = set(), []
        for row in inside:
            square = (row[1] // CELL, row[2] // CELL, row[3] // CELL)
            if row[4] != hub_id and square not in seen:
                seen.add(square)
                rest.append(row[:4])
        out[city] = (map_id, hubs[0][:4], sample(rest))
    return out


def quoted(name):
    return '"' + name.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(cities):
    lines = [
        "-- Generated by tools/gen_city_fixture.py - do not edit.",
        "-- Source: classic-db creature spawns that stand still, have an NPC flag and do not fly, inside each",
        "-- capital's zone map box: its flight master (Darnassus: its banker) as the hub, and an even sample of the",
        "-- rest, one per 8 yd square.",
        f"-- DB: https://github.com/cmangos/classic-db/tree/{DB_REV}",
        "-- Each place is { name, x, y, z } in world yards, z the height the server stores for the spawn.",
        "-- stylua: ignore",
        "return {",
    ]
    for city, (map_id, hub, rest) in cities.items():
        lines.append(f"\t[{quoted(city)}] = {{")
        lines.append(f"\t\tmap = {map_id},")
        lines.append(f"\t\thub = {{ {quoted(hub[0])}, {hub[1]}, {hub[2]}, {hub[3]} }},")
        lines.append("\t\tplaces = {")
        lines.extend(f"\t\t\t{{ {quoted(name)}, {x}, {y}, {z} }}," for name, x, y, z in rest)
        lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--offline", action="store_true", help="use the cached source only")
    args = parser.parse_args()
    publish({OUTPUT: render(places(creatures(args.offline)))})


if __name__ == "__main__":
    main()
